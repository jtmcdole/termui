typedef _FilterParamOps = ({
  double Function() read,
  void Function(double) write,
  void Function({required double to, required Duration time}) fade,
});

/// An audio buffer loaded into the Flutter backend.
final class FlutterAudioBuffer implements AudioBuffer {
  final sol.AudioSource _source;
  late final StreamSubscription<sol.StreamSoundEvent> _sub;

  /// Creates a new Flutter audio buffer.
  FlutterAudioBuffer(this._source, FlutterAudioEngine engine) {
    _sub = _source.soundEvents.listen((event) {
      if (event.event == sol.SoundEventType.handleIsNoMoreValid) {
        engine._completeVoice(event.handle.id);
      }
    });
  }

  /// The underlying SoLoud audio source.
  sol.AudioSource get source => _source;

  /// Disposes of the internal sound event listener subscription.
  void dispose() {
    unawaited(_sub.cancel());
  }

  /// The unique hash identifier generated by the SoLoud backend.
  @override
  int get hash => _source.soundHash.hash;
}

/// A mixing bus for grouping audio voices in the Flutter backend.
final class FlutterAudioBus implements AudioBus {
  final sol.Bus _bus;

  /// Creates a new Flutter audio bus.
  const FlutterAudioBus(this._bus);

  /// The unique ID of the bus.
  @override
  int get id => _bus.busId;

  /// Sets the volume for this bus.
  @override
  void setVolume(double volume) {
    final handle = _bus.soundHandle ?? sol.SoundHandle(_bus.busId);
    sol.SoLoud.instance.setVolume(handle, volume);
  }
}

/// The Flutter and Web implementation of [TermuiAudioEngine] backed by `flutter_soloud`.
class FlutterAudioEngine implements TermuiAudioEngine {
  sol.SoLoud get _engine => sol.SoLoud.instance;
  bool _inited = false;

  /// Whether this engine has been initialized and the underlying SoLoud backend is active.
  bool get isInitialized => _inited && _engine.isInitialized;

  final Map<int, Completer<void>> _activeVoices = {};
  final Map<int, sol.Bus> _buses = {};
  final Set<Timer> _activeTimers = {};
  sol.AudioData? _audioData;

  Timer _scheduleTimer(Duration duration, void Function() callback) {
    late final Timer timer;
    timer = Timer(duration, () {
      _activeTimers.remove(timer);
      callback();
    });
    _activeTimers.add(timer);
    return timer;
  }

  @override
  Duration getBufferDuration(AudioBuffer buffer) {
    if (buffer case FlutterAudioBuffer(:final source)) {
      return _engine.getLength(source);
    }
    return Duration.zero;
  }

  @override
  Duration getVoicePosition(AudioVoice voice) {
    return _engine.getPosition(sol.SoundHandle(voice.id));
  }

  @override
  Stream<Duration> getVoicePositionStream(
    AudioVoice voice, {
    Duration interval = const Duration(milliseconds: 50),
  }) => createVoicePositionStream(
    voice: voice,
    isVoiceActive: _activeVoices.containsKey,
    getPosition: getVoicePosition,
    interval: interval,
  );

  @override
  void seek(AudioVoice voice, Duration position) {
    _engine.seek(sol.SoundHandle(voice.id), position);
  }

  @override
  Future<void> init({bool enableVisualization = true}) async {
    if (!_engine.isInitialized) {
      await _engine.init();
      _engine.setVisualizationEnabled(enableVisualization);
      _audioData = sol.AudioData(sol.GetSamplesKind.wave);
    }
    _inited = true;
  }

  void _completeVoice(int voiceId) {
    final completer = _activeVoices.remove(voiceId);
    if (completer != null && !completer.isCompleted) {
      completer.complete();
    }
  }

  @override
  Future<void> dispose() async {
    for (final timer in _activeTimers) {
      timer.cancel();
    }
    _activeTimers.clear();

    for (final c in _activeVoices.values) {
      if (!c.isCompleted) c.complete();
    }
    _activeVoices.clear();

    if (_inited && _engine.isInitialized) {
      for (final solBus in _buses.values) {
        try {
          solBus.dispose();
        } catch (_) {}
      }
    }
    _buses.clear();

    _audioData?.dispose();
    _audioData = null;
    if (_inited && _engine.isInitialized) {
      _engine.deinit();
    }
    _inited = false;
  }

  @override
  Future<AudioBuffer> loadFile(
    String path, {
    bool stream = false,
    LoadProgressCallback? onProgress,
  }) async {
    onProgress?.call(0.1);
    final source = await _engine.loadFile(
      path,
      mode: stream ? sol.LoadMode.disk : sol.LoadMode.memory,
    );
    onProgress?.call(1.0);
    return FlutterAudioBuffer(source, this);
  }

  @override
  Future<AudioBuffer> loadUrl(
    String url, {
    LoadProgressCallback? onProgress,
  }) async {
    onProgress?.call(0.1);
    final source = await _engine.loadUrl(url);
    onProgress?.call(1.0);
    return FlutterAudioBuffer(source, this);
  }

  @override
  Future<Uint8List> loadFileBytes(String path) async {
    final byteData = await rootBundle.load(path);
    return Uint8List.sublistView(byteData);
  }

  @override
  Future<void> disposeBuffer(AudioBuffer buffer) async {
    if (buffer case FlutterAudioBuffer b) {
      b.dispose();
      await _engine.disposeSource(b.source);
    }
  }

  @override
  Future<AudioBuffer> loadMem(
    String pathId,
    Uint8List bytes, {
    bool stream = false,
  }) async {
    if (!isInitialized) throw Exception('Engine not initialized.');
    final source = await _engine.loadMem(
      pathId,
      bytes,
      mode: stream ? sol.LoadMode.disk : sol.LoadMode.memory,
    );
    return FlutterAudioBuffer(source, this);
  }

  @override
  Future<AudioBuffer> createBufferStream({
    int maxBufferSize = 4 * 1024 * 1024,
    bool releaseConsumed = false,
    Duration bufferingTimeNeeds = const Duration(milliseconds: 500),
    int sampleRate = 48000,
    int channels = 2,
  }) async {
    if (!isInitialized) throw Exception('Engine not initialized.');
    final source = _engine.setBufferStream(
      maxBufferSizeBytes: maxBufferSize,
      bufferingType: releaseConsumed
          ? sol.BufferingType.released
          : sol.BufferingType.preserved,
      bufferingTimeNeeds: bufferingTimeNeeds.inMicroseconds / 1000000.0,
      sampleRate: sampleRate,
      channels: channels == 1 ? sol.Channels.mono : sol.Channels.stereo,
      format: sol.BufferType.auto,
    );
    return FlutterAudioBuffer(source, this);
  }

  @override
  void addStreamData(AudioBuffer buffer, Uint8List chunk) {
    if (buffer case FlutterAudioBuffer b) {
      _engine.addAudioDataStream(b.source, chunk);
    }
  }

  @override
  void setStreamEnded(AudioBuffer buffer) {
    if (buffer case FlutterAudioBuffer b) {
      _engine.setDataIsEnded(b.source);
    }
  }

  @override
  Future<AudioBuffer> loadWaveform(
    WaveForm shape,
    double frequency, {
    bool usePcmFallback = false,
  }) async {
    if (usePcmFallback) {
      final pcmBytes = generateWaveformPcmWav(
        shape: shape,
        frequency: frequency,
      );
      final path = 'synthetic_${shape.name}_${frequency.toInt()}.wav';
      final source = await _engine.loadMem(path, pcmBytes);
      return FlutterAudioBuffer(source, this);
    }
    final solShape = sol.WaveForm.values.firstWhere(
      (e) => e.name == shape.name,
    );
    final source = await _engine.loadWaveform(solShape, true, 1.0, 0.0);
    _engine.setWaveformFreq(source, frequency);
    return FlutterAudioBuffer(source, this);
  }

  @override
  AudioVoice play(
    AudioBuffer buffer, {
    bool loop = false,
    AudioBus? bus,
    bool paused = false,
  }) {
    if (buffer case FlutterAudioBuffer(:final source)) {
      final busId = bus?.id ?? 0;
      final voice = _engine.play(
        source,
        looping: loop,
        busId: busId,
        paused: paused,
      );
      final completer = Completer<void>();
      _activeVoices[voice.id] = completer;
      return AudioVoice(voice.id, completer.future);
    }
    throw ArgumentError('Expected FlutterAudioBuffer');
  }

  @override
  void stop(AudioVoice voice) {
    _engine.stop(sol.SoundHandle(voice.id));
    _completeVoice(voice.id);
  }

  @override
  void setPaused(AudioVoice voice, bool paused) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    _engine.setPause(sol.SoundHandle(voice.id), paused);
  }

  @override
  void setVoiceVolume(AudioVoice voice, double volume) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    _engine.setVolume(sol.SoundHandle(voice.id), volume);
  }

  @override
  void setVoicePan(AudioVoice voice, double pan) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    final clamped = pan.isFinite ? pan.clamp(-1.0, 1.0).toDouble() : 0.0;
    _engine.setPan(sol.SoundHandle(voice.id), clamped);
  }

  @override
  AudioVoice play3d(AudioBuffer buffer, double x, double y, double z) {
    if (buffer case FlutterAudioBuffer(:final source)) {
      final voice = _engine.play3d(source, x, y, z);
      final completer = Completer<void>();
      _activeVoices[voice.id] = completer;
      return AudioVoice(voice.id, completer.future);
    }
    throw ArgumentError('Expected FlutterAudioBuffer');
  }

  @override
  void set3dSourceParameters(
    AudioVoice voice,
    double x,
    double y,
    double z, {
    double vx = 0.0,
    double vy = 0.0,
    double vz = 0.0,
  }) {
    _engine.set3dSourceParameters(
      sol.SoundHandle(voice.id),
      x,
      y,
      z,
      vx,
      vy,
      vz,
    );
  }

  @override
  void set3dSourceMinMaxDistance(
    AudioVoice voice,
    double minDistance,
    double maxDistance,
  ) {
    _engine.set3dSourceMinMaxDistance(
      sol.SoundHandle(voice.id),
      minDistance,
      maxDistance,
    );
  }

  @override
  void set3dSourceAttenuation(
    AudioVoice voice,
    AttenuationModel attenuationModel,
    double attenuationRolloffFactor,
  ) {
    _engine.set3dSourceAttenuation(
      sol.SoundHandle(voice.id),
      attenuationModel.index,
      attenuationRolloffFactor,
    );
  }

  @override
  void setRelativePlaySpeed(
    AudioVoice voice,
    double speed, {
    bool preservePitch = false,
  }) {
    if (preservePitch) {
      throw UnimplementedError(
        'preservePitch is not yet supported by FlutterAudioEngine; '
        'use CliAudioEngine or attach a pitchShift filter to an AudioBus.',
      );
    }
    if (!isInitialized) throw Exception('Engine not initialized.');
    _engine.setRelativePlaySpeed(sol.SoundHandle(voice.id), speed);
  }

  @override
  void fadeRelativePlaySpeed(
    AudioVoice voice,
    double speed,
    Duration duration,
  ) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    _engine.fadeRelativePlaySpeed(sol.SoundHandle(voice.id), speed, duration);
  }

  @override
  void fadeVolume(AudioVoice voice, double targetVolume, Duration duration) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    _engine.fadeVolume(sol.SoundHandle(voice.id), targetVolume, duration);
  }

  @override
  void scheduleStop(AudioVoice voice, Duration duration) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    _engine.scheduleStop(sol.SoundHandle(voice.id), duration);
  }

  @override
  int createFilter(FilterType type) => type.index;

  sol.Bus? _resolveSolBus(AudioBus bus) {
    final tracked = _buses[bus.id];
    if (tracked != null) return tracked;
    if (bus case FlutterAudioBus b) return b._bus;
    return null;
  }

  @override
  void attachFilterToBus(AudioBus bus, int filterId) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    if (filterId < 0 || filterId >= FilterType.values.length) {
      throw RangeError.index(filterId, FilterType.values, 'filterId');
    }
    final solBus = _resolveSolBus(bus);
    if (solBus == null) {
      throw StateError('AudioBus ${bus.id} is not registered on this engine.');
    }
    _activateBusFilter(solBus, FilterType.values[filterId]);
  }

  @override
  void setFilterParameter(
    AudioBus bus,
    int filterId,
    int paramId,
    double value,
  ) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    _lookupBusFilterParam(bus, filterId, paramId)?.write(value);
  }

  @override
  double getFilterParameter(AudioBus bus, int filterId, int paramId) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    return _lookupBusFilterParam(bus, filterId, paramId)?.read() ?? 0.0;
  }

  @override
  void fadeFilterParameter(
    AudioBus bus,
    int filterId,
    int paramId,
    double targetValue,
    Duration duration,
  ) {
    if (!isInitialized) throw Exception('Engine not initialized.');
    final ops = _lookupBusFilterParam(bus, filterId, paramId);
    if (ops == null) return;
    if (duration == Duration.zero) {
      ops.write(targetValue);
    } else {
      ops.fade(to: targetValue, time: duration);
    }
  }

  _FilterParamOps? _lookupBusFilterParam(
    AudioBus bus,
    int filterId,
    int paramId,
  ) {
    if (filterId < 0 || filterId >= FilterType.values.length) return null;
    final solBus = _resolveSolBus(bus);
    if (solBus == null) return null;
    return switch (FilterType.values[filterId]) {
      FilterType.biquadResonant => _biquadParamOps(solBus, paramId),
      FilterType.echo => _echoParamOps(solBus, paramId),
      FilterType.lofi => _lofiParamOps(solBus, paramId),
      FilterType.flanger => _flangerParamOps(solBus, paramId),
      FilterType.bassboost => _bassBoostParamOps(solBus, paramId),
      FilterType.waveShaper => _waveShaperParamOps(solBus, paramId),
      FilterType.robotize => _robotizeParamOps(solBus, paramId),
      FilterType.freeverb => _freeverbParamOps(solBus, paramId),
      FilterType.pitchShift => _pitchShiftParamOps(solBus, paramId),
      FilterType.limiter => _limiterParamOps(solBus, paramId),
      FilterType.compressor => _compressorParamOps(solBus, paramId),
      FilterType.parametricEq => _parametricEqParamOps(solBus, paramId),
    };
  }

  @override
  AudioVoice playSprite(
    AudioBuffer buffer, {
    AudioBus? bus,
    required Duration start,
    required Duration duration,
  }) {
    final voice = play(buffer, bus: bus, paused: true);
    if (start > Duration.zero) {
      seek(voice, start);
    }
    setPaused(voice, false);
    scheduleStop(voice, duration);
    return voice;
  }

  @override
  Future<void> playSpriteSequence(
    AudioBuffer buffer,
    List<SpriteSegment> segments, {
    AudioBus? bus,
  }) {
    if (!isInitialized || segments.isEmpty) return Future<void>.value();

    final completer = Completer<void>();
    var remaining = segments.length;
    var totalDelay = Duration.zero;

    void onSegmentEnded() {
      if (--remaining <= 0 && !completer.isCompleted) {
        completer.complete();
      }
    }

    for (final seg in segments) {
      final segDelay = totalDelay;
      totalDelay += seg.duration;
      void startSegment() =>
          _playSpriteSegment(buffer, seg, bus, onSegmentEnded);
      if (segDelay == Duration.zero) {
        startSegment();
      } else {
        _scheduleTimer(segDelay, startSegment);
      }
    }

    return completer.future;
  }

  void _playSpriteSegment(
    AudioBuffer buffer,
    SpriteSegment seg,
    AudioBus? bus,
    void Function() onSegmentEnded,
  ) {
    if (!isInitialized) {
      onSegmentEnded();
      return;
    }
    final voice = play(buffer, bus: bus, paused: true);
    if (seg.start > Duration.zero) {
      seek(voice, seg.start);
    }
    setPaused(voice, false);
    scheduleStop(voice, seg.duration);
    unawaited(voice.completed.whenComplete(onSegmentEnded));
  }

  @override
  AudioBus createBus() {
    if (!isInitialized) throw Exception('Engine not initialized.');
    final solBus = sol.Bus();
    solBus.playOnEngine();
    _buses[solBus.busId] = solBus;
    return FlutterAudioBus(solBus);
  }

  @override
  void destroyBus(AudioBus bus) {
    final solBus = _buses.remove(bus.id);
    if (!isInitialized) return;
    if (solBus != null) {
      solBus.dispose();
    } else if (bus case FlutterAudioBus b) {
      b._bus.dispose();
    }
  }

  @override
  Float32List getWaveform([Float32List? outBuffer]) {
    if (outBuffer != null && outBuffer.length < 256) {
      throw ArgumentError('outBuffer must be at least 256 elements long.');
    }
    final buffer = outBuffer ?? Float32List(256);
    if (_audioData == null) return buffer;

    _audioData!.updateSamples();
    final data = _audioData!.getAudioData(alwaysReturnData: true);
    buffer.setAll(0, data);
    return buffer;
  }
}

void _activateBusFilter(sol.Bus solBus, FilterType filter) {
  final f = solBus.filters;
  switch (filter) {
    case FilterType.biquadResonant:
      f.biquadFilter.activate();
    case FilterType.echo:
      f.echoFilter.activate();
    case FilterType.lofi:
      f.lofiFilter.activate();
    case FilterType.flanger:
      f.flangerFilter.activate();
    case FilterType.bassboost:
      f.bassBoostFilter.activate();
    case FilterType.waveShaper:
      f.waveShaperFilter.activate();
    case FilterType.robotize:
      f.robotizeFilter.activate();
    case FilterType.freeverb:
      f.freeverbFilter.activate();
    case FilterType.pitchShift:
      f.pitchShiftFilter.activate();
    case FilterType.limiter:
      f.limiterFilter.activate();
    case FilterType.compressor:
      f.compressorFilter.activate();
    case FilterType.parametricEq:
      f.parametricEqFilter.activate();
  }
}

_FilterParamOps? _biquadParamOps(sol.Bus bus, int paramId) {
  final f = bus.filters.biquadFilter;
  final p = switch (paramId) {
    0 => f.wet(),
    1 => f.type(),
    2 => f.frequency(),
    3 => f.resonance(),
    _ => null,
  };
  if (p == null) return null;
  return (
    read: () => p.value,
    write: (v) => p.value = v,
    fade: p.fadeFilterParameter,
  );
}

