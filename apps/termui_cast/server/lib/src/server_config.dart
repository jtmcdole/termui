import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:args/args.dart';
import 'package:path/path.dart' as p;

/// Validated startup configuration for the stateless relay server.
final class ServerConfig {
  /// Default TCP port when neither `--port` nor `$PORT` is specified.
  static const int defaultPort = 8420;

  /// Network interface address to bind.
  final InternetAddress host;

  /// TCP port to bind (`0` selects an ephemeral port).
  final int port;

  /// Optional bearer token required from caster peers.
  final String? casterToken;

  /// Optional bearer token required from viewer client peers.
  final String? clientToken;

  /// Whether [casterToken] was auto-minted at startup for a loopback bind.
  final bool autoGeneratedCasterToken;

  /// Whether [clientToken] was auto-minted at startup for a loopback bind.
  final bool autoGeneratedClientToken;

  /// Optional directory containing built Flutter web assets (`index.html`).
  final String? webRoot;

  /// Optional active server revision identifier advertised via `x-cast-revision`.
  final String? revision;

  /// Maximum duration allowed for a peer to send its initial `AuthFrame`.
  final Duration authTimeout;

  /// Whether `/v1/client` trusts upstream perimeter auth instead of a client bearer token.
  final bool trustProxyClientAuth;

  /// Optional lowercase HTTP header name required on `/v1/client` upgrades when [trustProxyClientAuth] is enabled.
  final String? requireClientAuthHeader;

  /// Normalized URL subpath prefix (`''` for root, or `/prefix` without trailing slash).
  final String basePath;

  /// Canonicalized `http://` or `https://` origins explicitly allowed on WebSocket upgrades.
  final Set<String> allowedOrigins;

  final List<({String scheme, String host, int port})> _allowedOriginEndpoints;

  /// Non-fatal startup configuration warnings (e.g. secrets passed on CLI argv).
  final List<String> warnings;

  /// Creates a validated relay server configuration.
  ServerConfig({
    InternetAddress? host,
    this.port = defaultPort,
    this.casterToken,
    this.clientToken,
    this.autoGeneratedCasterToken = false,
    this.autoGeneratedClientToken = false,
    this.trustProxyClientAuth = false,
    String? requireClientAuthHeader,
    String basePath = '',
    this.webRoot,
    String? revision,
    this.authTimeout = const Duration(seconds: 2),
    Iterable<String> allowedOrigins = const [],
    List<String> warnings = const [],
  }) : host = host ?? InternetAddress.loopbackIPv4,
       requireClientAuthHeader = _normalizeRequiredClientAuthHeader(
         requireClientAuthHeader,
       ),
       basePath = _normalizeBasePath(basePath),
       revision = _normalizeRevision(revision),
       allowedOrigins = Set<String>.unmodifiable({
         for (final raw in allowedOrigins) _parseRequiredHttpOrigin(raw).origin,
       }),
       _allowedOriginEndpoints = List.unmodifiable([
         for (final raw in allowedOrigins)
           _toOriginEndpoint(_parseRequiredHttpOrigin(raw)),
       ]),
       warnings = List<String>.unmodifiable(warnings) {
    _validateConfig();
  }

  void _validateConfig() {
    if (port < 0 || port > 65535) {
      throw FormatException('Port must be in 0..65535, got $port');
    }
    if (webRoot != null && !_hasValidIndexHtml(webRoot!)) {
      throw FormatException(
        'Static web directory not found or missing index.html: "$webRoot"',
      );
    }
    final hasCaster = casterToken != null && casterToken!.isNotEmpty;
    final hasClient = clientToken != null && clientToken!.isNotEmpty;
    if (requireClientAuthHeader != null && !trustProxyClientAuth) {
      throw const FormatException(
        '--require-client-auth-header requires --trust-proxy-client-auth',
      );
    }
    if (trustProxyClientAuth && hasClient) {
      throw const FormatException(
        '--trust-proxy-client-auth cannot be combined with '
        '--client-token or --client-token-file',
      );
    }
    if (!host.isLoopback && !hasCaster) {
      throw FormatException(
        'Non-loopback host ${host.address} requires '
        '${trustProxyClientAuth ? '--caster-token' : 'both --caster-token and --client-token'}',
      );
    }
    if (!host.isLoopback && !trustProxyClientAuth && !hasClient) {
      throw FormatException(
        'Non-loopback host ${host.address} requires both '
        '--caster-token and --client-token',
      );
    }
  }

  /// Returns whether the HTTP `Host` header [requestHostHeader] is valid for
  /// this server's bind address (blocking DNS rebinding when bound to loopback,
  /// while permitting proxied hosts explicitly listed in [allowedOrigins]).
  bool isRequestHostAllowed(String? requestHostHeader) {
    if (!host.isLoopback) return true;
    if (requestHostHeader == null || requestHostHeader.trim().isEmpty) {
      return true;
    }
    final parsedHost = _parseHostHeader(requestHostHeader);
    if (parsedHost == null) return false;
    return _isLoopbackHost(parsedHost.host) ||
        _matchesAllowedOriginHost(parsedHost);
  }

  bool _matchesAllowedOriginHost(({String host, int? port}) reqHost) {
    for (final origin in _allowedOriginEndpoints) {
      if (origin.host != reqHost.host) continue;
      final expectedPort =
          reqHost.port ?? (origin.scheme == 'https' ? 443 : 80);
      if (origin.port == expectedPort) return true;
    }
    return false;
  }

  /// Returns whether a WebSocket upgrade carrying [originHeaders] and
  /// [requestHostHeader] is permitted under loopback, same-host, or [allowedOrigins] rules.
  bool isOriginAllowed(
    List<String>? originHeaders, {
    String? requestHostHeader,
    String? forwardedProtoHeader,
  }) {
    if (!isRequestHostAllowed(requestHostHeader)) return false;
    if (originHeaders == null) return true;
    if (originHeaders.length != 1) return false;
    final parsed = _tryParseHttpOrigin(originHeaders.single);
    if (parsed == null) return false;
    if (host.isLoopback) {
      return _isLoopbackHost(parsed.host) ||
          allowedOrigins.contains(parsed.origin);
    }
    if (_matchesSameHostOrigin(
      parsed,
      requestHostHeader,
      forwardedProtoHeader,
    )) {
      return true;
    }
    return allowedOrigins.contains(parsed.origin);
  }

  bool _matchesSameHostOrigin(
    ({String origin, String scheme, String host, int port, bool hasPort})
    parsed,
    String? requestHostHeader,
    String? forwardedProtoHeader,
  ) {
    final reqHost = _parseHostHeader(requestHostHeader);
    if (reqHost == null || parsed.host != reqHost.host) return false;
    final requireHttps = _isHttpsForwardedProto(forwardedProtoHeader);
    if (requireHttps && parsed.scheme != 'https') return false;
    return reqHost.port != null ? parsed.port == reqHost.port : !parsed.hasPort;
  }

  /// Validates and canonicalizes an optional subpath mount prefix (`''` for
  /// root, or `/prefix` without a trailing slash), rejecting empty segments,
  /// traversal segments, HTML-special characters, or `/v1` collisions.
  static String normalizeBasePath(String raw) => _normalizeBasePath(raw);

  /// Builds the command-line argument parser for `termui_cast_server`.
  static ArgParser buildArgParser() {
    return ArgParser()
      ..addFlag('help', abbr: 'h', negatable: false, help: 'Show CLI usage.')
      ..addOption(
        'host',
        defaultsTo: '127.0.0.1',
        help:
            'Interface IP address to bind (defaults to 0.0.0.0 when \$PORT is set).',
      )
      ..addOption(
        'port',
        abbr: 'p',
        defaultsTo: '$defaultPort',
        help: 'TCP port to listen on (falls back to \$PORT).',
      )
      ..addOption(
        'caster-token',
        help:
            'Bearer token required on /v1/caster (or \$TERMUI_CAST_CASTER_TOKEN). Prefer --caster-token-file or env.',
      )
      ..addOption(
        'caster-token-file',
        help:
            'File containing the /v1/caster bearer token (or \$TERMUI_CAST_CASTER_TOKEN_FILE).',
      )
      ..addOption(
        'client-token',
        help:
            'Bearer token required on /v1/client (or \$TERMUI_CAST_CLIENT_TOKEN). Prefer --client-token-file or env.',
      )
      ..addOption(
        'client-token-file',
        help:
            'File containing the /v1/client bearer token (or \$TERMUI_CAST_CLIENT_TOKEN_FILE).',
      )
      ..addFlag(
        'insecure-no-auth',
        negatable: false,
        help: 'Disable bearer token authentication on loopback binds.',
      )
      ..addFlag(
        'trust-proxy-client-auth',
        negatable: false,
        help:
            'Allow tokenless /v1/client upgrades behind perimeter auth (or \$TERMUI_CAST_TRUST_PROXY_CLIENT_AUTH).',
      )
      ..addOption(
        'require-client-auth-header',
        help:
            'Require a non-empty HTTP header on /v1/client when --trust-proxy-client-auth is set (or \$TERMUI_CAST_REQUIRE_CLIENT_AUTH_HEADER).',
      )
      ..addOption(
        'base-path',
        help:
            'Mount relay and static routes under a URL subpath prefix such as /term (or \$TERMUI_CAST_BASE_PATH).',
      )
      ..addOption(
        'web-dir',
        help:
            'Static Flutter web directory to serve at / (or \$TERMUI_CAST_WEB_DIR).',
      )
      ..addFlag(
        'no-web',
        negatable: false,
        help: 'Disable static web asset hosting even when build/web exists.',
      )
      ..addOption(
        'revision',
        help:
            'Server revision advertised in x-cast-revision (or \$TERMUI_CAST_REVISION / \$K_REVISION).',
      )
      ..addMultiOption(
        'allowed-origin',
        help:
            'Additional http(s) Origin header allowed (or \$TERMUI_CAST_ALLOWED_ORIGINS).',
      );
  }

  /// Parses CLI [args] and [environment] once at startup into a validated
  /// [ServerConfig], or returns `null` when `--help` was requested.
  static ServerConfig? fromArgs(
    List<String> args, {
    Map<String, String>? environment,
    Directory? currentDirectory,
    String? resolvedExecutable,
  }) {
    final results = buildArgParser().parse(args);
    if (results['help'] as bool) return null;
    if (results.rest.isNotEmpty) {
      throw FormatException('Unexpected positional args: ${results.rest}');
    }

    final env = environment ?? Platform.environment;
    final cwd = currentDirectory ?? Directory.current;

    final host = _resolveHost(results, env);
    final insecureNoAuth = results['insecure-no-auth'] as bool;
    final trustProxyClientAuth = _resolveTrustProxyClientAuth(results, env);
    final requireClientAuthHeader = _resolveRequireClientAuthHeader(
      results,
      env,
    );
    _validateAuthFlagCombinations(
      host: host,
      insecureNoAuth: insecureNoAuth,
      trustProxyClientAuth: trustProxyClientAuth,
      requireClientAuthHeader: requireClientAuthHeader,
      results: results,
      env: env,
    );

    final warnings = _collectArgvTokenWarnings(results);
    final autoMint = host.isLoopback && !insecureNoAuth;
    final casterAuth = _resolveToken(
      results,
      'caster-token',
      'caster-token-file',
      env,
      'TERMUI_CAST_CASTER_TOKEN',
      'TERMUI_CAST_CASTER_TOKEN_FILE',
      autoMint: autoMint,
    );
    final clientAuth = trustProxyClientAuth
        ? (token: null, autoGenerated: false)
        : _resolveToken(
            results,
            'client-token',
            'client-token-file',
            env,
            'TERMUI_CAST_CLIENT_TOKEN',
            'TERMUI_CAST_CLIENT_TOKEN_FILE',
            autoMint: autoMint,
          );

    return ServerConfig(
      host: host,
      port: _resolvePort(results, env),
      casterToken: casterAuth.token,
      clientToken: clientAuth.token,
      autoGeneratedCasterToken: casterAuth.autoGenerated,
      autoGeneratedClientToken: clientAuth.autoGenerated,
      trustProxyClientAuth: trustProxyClientAuth,
      requireClientAuthHeader: requireClientAuthHeader,
      basePath: _resolveBasePath(results, env),
      webRoot: _resolveWebRoot(
        results,
        env,
        cwd,
        resolvedExecutable: resolvedExecutable,
      ),
      revision: _resolveRevision(results, env),
      allowedOrigins: _resolveAllowedOrigins(results, env),
      warnings: warnings,
    );
  }

  static void _validateAuthFlagCombinations({
    required InternetAddress host,
    required bool insecureNoAuth,
    required bool trustProxyClientAuth,
    required String? requireClientAuthHeader,
    required ArgResults results,
    required Map<String, String> env,
  }) {
    if (insecureNoAuth && !host.isLoopback) {
      throw const FormatException(
        '--insecure-no-auth is only permitted on loopback hosts (127.0.0.1 / ::1)',
      );
    }
    if (trustProxyClientAuth && insecureNoAuth) {
      throw const FormatException(
        '--trust-proxy-client-auth cannot be combined with --insecure-no-auth',
      );
    }
    if (requireClientAuthHeader != null && !trustProxyClientAuth) {
      throw const FormatException(
        '--require-client-auth-header requires --trust-proxy-client-auth',
      );
    }
    if (trustProxyClientAuth && _hasConfiguredClientToken(results, env)) {
      throw const FormatException(
        '--trust-proxy-client-auth cannot be combined with --client-token, '
        '--client-token-file, TERMUI_CAST_CLIENT_TOKEN, or TERMUI_CAST_CLIENT_TOKEN_FILE',
      );
    }
  }

  static bool _hasConfiguredClientToken(
    ArgResults results,
    Map<String, String> env,
  ) =>
      results.wasParsed('client-token') ||
      results.wasParsed('client-token-file') ||
      _nonEmpty(env['TERMUI_CAST_CLIENT_TOKEN']) != null ||
      _nonEmpty(env['TERMUI_CAST_CLIENT_TOKEN_FILE']) != null;

  static List<String> _collectArgvTokenWarnings(ArgResults results) => [
    if (results.wasParsed('caster-token') &&
        _nonEmpty(results['caster-token'] as String?) != null)
      '--caster-token on the CLI is visible via process listings behind your bastion; prefer --caster-token-file or TERMUI_CAST_CASTER_TOKEN.',
    if (results.wasParsed('client-token') &&
        _nonEmpty(results['client-token'] as String?) != null)
      '--client-token on the CLI is visible via process listings behind your bastion; prefer --client-token-file or TERMUI_CAST_CLIENT_TOKEN.',
  ];

  static bool _resolveTrustProxyClientAuth(
    ArgResults results,
    Map<String, String> env,
  ) {
    if (results.wasParsed('trust-proxy-client-auth')) {
      return results['trust-proxy-client-auth'] as bool;
    }
    final raw = env['TERMUI_CAST_TRUST_PROXY_CLIENT_AUTH']
        ?.trim()
        .toLowerCase();
    return raw == 'true' || raw == '1';
  }

  static String? _resolveRequireClientAuthHeader(
    ArgResults results,
    Map<String, String> env,
  ) {
    if (results.wasParsed('require-client-auth-header')) {
      return results['require-client-auth-header'] as String?;
    }
    return _nonEmpty(env['TERMUI_CAST_REQUIRE_CLIENT_AUTH_HEADER']);
  }

  static String _resolveBasePath(ArgResults results, Map<String, String> env) {
    if (results.wasParsed('base-path')) {
      return results['base-path'] as String;
    }
    return _nonEmpty(env['TERMUI_CAST_BASE_PATH']) ?? '';
  }

  static ({String? token, bool autoGenerated}) _resolveToken(
    ArgResults results,
    String optionName,
    String fileOptionName,
    Map<String, String> env,
    String envName,
    String fileEnvName, {
    required bool autoMint,
  }) {
    final cliInline = results.wasParsed(optionName)
        ? _nonEmpty(results[optionName] as String?)
        : null;
    final cliFile = results.wasParsed(fileOptionName)
        ? _nonEmpty(results[fileOptionName] as String?)
        : null;
    if (cliInline != null && cliFile != null) {
      throw FormatException(
        'Cannot specify both --$optionName and --$fileOptionName.',
      );
    }
    final configured =
        cliInline ??
        (cliFile != null
            ? _readTokenFile(cliFile, '--$fileOptionName')
            : null) ??
        _nonEmpty(env[envName]) ??
        (_nonEmpty(env[fileEnvName]) != null
            ? _readTokenFile(_nonEmpty(env[fileEnvName])!, '\$$fileEnvName')
            : null);
    if (configured != null || !autoMint) {
      return (token: configured, autoGenerated: false);
    }
    return (token: _mintRandomToken(), autoGenerated: true);
  }

  static String _readTokenFile(String path, String sourceLabel) {
    final file = File(path);
    try {
      final contents = file.readAsStringSync().trim();
      if (contents.isEmpty) {
        throw FormatException('Token file from $sourceLabel is empty: "$path"');
      }
      return contents;
    } on FileSystemException catch (e) {
      throw FormatException(
        'Unable to read token file from $sourceLabel ("$path"): ${e.message}',
      );
    }
  }

  static String _mintRandomToken() {
    final random = Random.secure();
    final bytes = List<int>.generate(24, (_) => random.nextInt(256));
    return base64UrlEncode(bytes).replaceAll('=', '');
  }

  static InternetAddress _resolveHost(
    ArgResults results,
    Map<String, String> env,
  ) {
    final envPort = _nonEmpty(env['PORT']);
    final rawHost = results.wasParsed('host')
        ? results['host'] as String
        : (_nonEmpty(env['HOST']) ??
              (envPort != null ? '0.0.0.0' : '127.0.0.1'));
    final host = rawHost == 'localhost'
        ? InternetAddress.loopbackIPv4
        : InternetAddress.tryParse(rawHost);
    if (host == null) {
      throw FormatException('Invalid --host IP address: "$rawHost"');
    }
    return host;
  }

  static int _resolvePort(ArgResults results, Map<String, String> env) {
    final rawPort = results.wasParsed('port')
        ? results['port'] as String
        : (_nonEmpty(env['PORT']) ?? '$defaultPort');
    final port = int.tryParse(rawPort);
    if (port == null) {
      throw FormatException('Invalid --port integer: "$rawPort"');
    }
    return port;
  }

  static String? _resolveRevision(ArgResults results, Map<String, String> env) {
    if (results.wasParsed('revision')) {
      return results['revision'] as String?;
    }
    return _nonEmpty(env['TERMUI_CAST_REVISION']) ??
        _nonEmpty(env['K_REVISION']);
  }

  static String? _normalizeRevision(String? raw) {
    if (raw == null) return null;
    final trimmed = raw.trim();
    if (trimmed.isEmpty || trimmed.length > 128) {
      throw FormatException(
        'Invalid revision "$raw": must be 1..128 visible ASCII characters (0x21..0x7E).',
      );
    }
    for (var i = 0; i < trimmed.length; i++) {
      final unit = trimmed.codeUnitAt(i);
      if (unit < 0x21 || unit > 0x7E) {
        throw FormatException(
          'Invalid revision "$raw": must be 1..128 visible ASCII characters (0x21..0x7E).',
        );
      }
    }
    return trimmed;
  }

  static Iterable<String> _resolveAllowedOrigins(
    ArgResults results,
    Map<String, String> env,
  ) {
    if (results.wasParsed('allowed-origin')) {
      return results['allowed-origin'] as List<String>;
    }
    final rawEnv = _nonEmpty(env['TERMUI_CAST_ALLOWED_ORIGINS']);
    if (rawEnv == null) return const [];
    return [
      for (final part in rawEnv.split(','))
        if (part.trim().isNotEmpty) part.trim(),
    ];
  }

  static const Set<String> _dartRuntimeBasenames = {
    'dart',
    'dart.exe',
    'dartaotruntime',
    'dartaotruntime.exe',
    'flutter_tester',
    'flutter_tester.exe',
  };

  static List<String> _executableWebCandidates(String exePath) {
    if (exePath.isEmpty) return const [];
    final base = p.basename(exePath).toLowerCase();
    if (_dartRuntimeBasenames.contains(base)) return const [];
    final exeDir = p.dirname(exePath);
    return [p.join(exeDir, '..', 'web'), p.join(exeDir, 'web')];
  }

  static String? _resolveWebRoot(
    ArgResults results,
    Map<String, String> env,
    Directory cwd, {
    String? resolvedExecutable,
  }) {
    if (results['no-web'] as bool) return null;
    if (results.wasParsed('web-dir')) {
      return results['web-dir'] as String;
    }
    if (env.containsKey('TERMUI_CAST_WEB_DIR')) {
      return _nonEmpty(env['TERMUI_CAST_WEB_DIR']);
    }
    final exePath = resolvedExecutable ?? Platform.resolvedExecutable;
    final candidates = [
      ..._executableWebCandidates(exePath),
      p.join(cwd.path, 'apps', 'fterm', 'build', 'web'),
      p.join(cwd.path, '..', '..', 'fterm', 'build', 'web'),
      p.join(cwd.path, '..', '..', '..', 'apps', 'fterm', 'build', 'web'),
    ];
    for (final candidate in candidates) {
      final normalized = p.normalize(candidate);
      if (_hasValidIndexHtml(normalized)) return normalized;
    }
    return null;
  }
}

bool _hasValidIndexHtml(String dirPath) =>
    Directory(dirPath).existsSync() &&
    (File(p.join(dirPath, 'index.html')).existsSync() ||
        File(p.join(dirPath, 'index.html.gz')).existsSync());

String? _nonEmpty(String? value) {
  final trimmed = value?.trim();
  return trimmed == null || trimmed.isEmpty ? null : trimmed;
}

final RegExp _httpHeaderTokenPattern = RegExp(
  r"^[!#$%&'*+\-.^_`|~0-9A-Za-z]+$",
);

String? _normalizeRequiredClientAuthHeader(String? raw) {
  if (raw == null) return null;
  if (raw.isEmpty || !_httpHeaderTokenPattern.hasMatch(raw)) {
    throw FormatException(
      'Invalid --require-client-auth-header "$raw": expected a valid RFC 9110 HTTP header token.',
    );
  }
  return raw.toLowerCase();
}

String _normalizeBasePath(String raw) {
  if (raw.isEmpty || raw == '/') return '';
  if (_hasInvalidBasePathChars(raw) || raw.contains('//')) {
    throw FormatException(
      'Invalid --base-path "$raw": must be a clean URL path prefix without empty segments, query, fragment, or control characters.',
    );
  }
  final withLeading = raw.startsWith('/') ? raw : '/$raw';
  final normalized = withLeading.endsWith('/')
      ? withLeading.substring(0, withLeading.length - 1)
      : withLeading;
  final segments = normalized.substring(1).split('/');
  for (final segment in segments) {
    if (!_isValidBasePathSegment(segment)) {
      throw FormatException(
        'Invalid --base-path "$raw": segment "$segment" is not allowed.',
      );
    }
  }
  if (segments.first == 'v1') {
    throw FormatException(
      'Invalid --base-path "$raw": cannot collide with the /v1 WebSocket namespace.',
    );
  }
  return normalized;
}

bool _hasInvalidBasePathChars(String value) {
  for (var i = 0; i < value.length; i++) {
    final unit = value.codeUnitAt(i);
    if (unit <= 0x20 ||
        unit == 0x7F ||
        unit == 0x3F || // '?'
        unit == 0x23 || // '#'
        unit == 0x5C || // '\'
        unit == 0x22 || // '"'
        unit == 0x27 || // "'"
        unit == 0x3C || // '<'
        unit == 0x3E || // '>'
        unit == 0x60) {
      // '`'
      return true;
    }
  }
  return false;
}

bool _isValidBasePathSegment(String segment) {
  if (segment.isEmpty || segment == '.' || segment == '..') return false;
  final String decoded;
  try {
    decoded = Uri.decodeComponent(segment);
  } on ArgumentError {
    return false;
  }
  return decoded.isNotEmpty &&
      decoded != '.' &&
      decoded != '..' &&
      !decoded.contains('/') &&
      !decoded.contains(r'\') &&
      !decoded.contains('\x00');
}

({String origin, String scheme, String host, int port, bool hasPort})
_parseRequiredHttpOrigin(String raw) {
  final parsed = _tryParseHttpOrigin(raw);
  if (parsed == null) {
    throw FormatException(
      'Invalid --allowed-origin "$raw": expected http:// or https:// origin.',
    );
  }
  return parsed;
}

({String scheme, String host, int port}) _toOriginEndpoint(
  ({String origin, String scheme, String host, int port, bool hasPort}) parsed,
) => (scheme: parsed.scheme, host: parsed.host, port: parsed.port);

({String origin, String scheme, String host, int port, bool hasPort})?
_tryParseHttpOrigin(String raw) {
  final uri = Uri.tryParse(raw.trim());
  if (uri == null || !_isValidHttpOriginUri(uri)) return null;
  final host = _stripBrackets(uri.host).toLowerCase();
  final canonical = Uri(
    scheme: uri.scheme,
    host: host,
    port: uri.hasPort ? uri.port : null,
  );
  return (
    origin: '$canonical',
    scheme: uri.scheme,
    host: host,
    port: uri.port,
    hasPort: uri.hasPort,
  );
}

bool _isValidHttpOriginUri(Uri uri) =>
    (uri.scheme == 'http' || uri.scheme == 'https') &&
    uri.host.isNotEmpty &&
    uri.userInfo.isEmpty &&
    !uri.hasQuery &&
    !uri.hasFragment &&
    (uri.path.isEmpty || uri.path == '/');

bool _isLoopbackHost(String host) {
  if (host == 'localhost' || host == '127.0.0.1' || host == '::1') {
    return true;
  }
  return InternetAddress.tryParse(host)?.isLoopback ?? false;
}

({String host, int? port})? _parseHostHeader(String? rawHostHeader) {
  if (rawHostHeader == null) return null;
  final trimmed = rawHostHeader.trim();
  if (trimmed.isEmpty) return null;
  final uri = Uri.tryParse('cast://$trimmed');
  if (uri == null ||
      uri.host.isEmpty ||
      uri.userInfo.isNotEmpty ||
      uri.path.isNotEmpty ||
      uri.hasQuery ||
      uri.hasFragment) {
    return null;
  }
  return (
    host: _stripBrackets(uri.host).toLowerCase(),
    port: uri.hasPort ? uri.port : null,
  );
}

String _stripBrackets(String host) {
  if (host.length >= 2 && host.startsWith('[') && host.endsWith(']')) {
    return host.substring(1, host.length - 1);
  }
  return host;
}

bool _isHttpsForwardedProto(String? header) {
  if (header == null) return false;
  final first = header.split(',').first.trim().toLowerCase();
  return first == 'https';
}
