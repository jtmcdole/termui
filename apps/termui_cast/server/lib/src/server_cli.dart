import 'dart:async';
import 'dart:io';

import 'package:termui_cast_protocol/termui_cast_protocol_io.dart';

import 'cast_server.dart';
import 'server_config.dart';

/// Runs the `termui_cast_server` CLI with [args], returning the process exit code.
Future<int> runServerCli(
  List<String> args, {
  StringSink? out,
  StringSink? err,
  Stream<void>? shutdownSignal,
  Map<String, String>? environment,
}) async {
  final stdoutSink = out ?? stdout;
  final stderrSink = err ?? stderr;
  final env = environment ?? Platform.environment;

  final ServerConfig? config;
  try {
    config = ServerConfig.fromArgs(args, environment: env);
  } on FormatException catch (e) {
    stderrSink
      ..writeln('Error: ${e.message}')
      ..writeln(ServerConfig.buildArgParser().usage);
    return 64;
  }

  if (config == null) {
    stdoutSink
      ..writeln('Usage: termui_cast_server [options]')
      ..writeln(ServerConfig.buildArgParser().usage);
    return 0;
  }

  for (final warning in config.warnings) {
    stderrSink.writeln('[termui_cast_server] WARNING: $warning');
  }

  final isCloudRun = env['K_SERVICE']?.isNotEmpty ?? false;
  if (!config.host.isLoopback && !isCloudRun) {
    stderrSink.writeln(
      '[termui_cast_server] WARNING: Binding non-loopback '
      '${config.host.address} over plaintext ws://. Terminate TLS at a '
      'reverse proxy, bastion, SSH tunnel, or Cloud Run IAP in front of the relay.',
    );
  }

  final CastServer server;
  try {
    server = await CastServer.bind(
      config,
      onLog: (msg) => stderrSink.writeln('[termui_cast_server] $msg'),
    );
  } on SocketException catch (e) {
    stderrSink.writeln(
      'Error: Failed to bind ${config.host.address}:${config.port}: ${e.message}',
    );
    return 78;
  } on FileSystemException catch (e) {
    stderrSink.writeln('Error: ${e.message}');
    return 78;
  }
  stdoutSink.writeln(
    'Listening on ${server.casterUri} and ${server.clientUri}',
  );
  if (config.autoGeneratedCasterToken) {
    stdoutSink.writeln(
      'Auto-generated caster token (TERMUI_CAST_CASTER_TOKEN): '
      '${config.casterToken}',
    );
  }
  if (config.autoGeneratedClientToken) {
    stdoutSink.writeln(
      'Auto-generated client token (TERMUI_CAST_CLIENT_TOKEN): '
      '${config.clientToken}',
    );
  }
  if (config.webRoot != null) {
    stdoutSink.writeln('Serving static web client from ${config.webRoot}');
  }

  final stopStream = shutdownSignal ?? watchPosixTerminationSignals();
  await stopStream.first;
  await server.close();
  return 0;
}
