  group('CastServer static web pass-through and /healthz', () {
    late Directory rootSandbox;
    late Directory webDir;
    late File outsideSecret;
    late CastServer server;

    setUp(() async {
      rootSandbox = await Directory.systemTemp.createTemp('cast_static_srv_');
      webDir = await Directory(p.join(rootSandbox.path, 'web')).create();
      outsideSecret = File(p.join(rootSandbox.path, 'secret.txt'));
      await outsideSecret.writeAsString('TOP_SECRET');

      await File(
        p.join(webDir.path, 'index.html'),
      ).writeAsString('<!doctype html><html><body>CastApp</body></html>');
      await File(
        p.join(webDir.path, 'main.dart.mjs'),
      ).writeAsString('export const ok = true;');
      await File(
        p.join(webDir.path, 'main.dart.wasm'),
      ).writeAsBytes(const [0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00]);
      final fontsDir = await Directory(
        p.join(webDir.path, 'assets', 'fonts'),
      ).create(recursive: true);
      await File(
        p.join(fontsDir.path, 'CascadiaMonoPL.ttf'),
      ).writeAsBytes(const [1, 2, 3, 4]);
      await File(
        p.join(fontsDir.path, 'Cascadia Mono.ttf'),
      ).writeAsBytes(const [5, 6, 7, 8]);

      server = await CastServer.bind(
        ServerConfig(port: 0, webRoot: webDir.path),
      );
    });

    tearDown(() async {
      await server.close();
      await rootSandbox.delete(recursive: true);
    });

    Future<({int statusCode, HttpHeaders headers, List<int> body})> sendRequest(
      String method,
      String path,
    ) async {
      final client = HttpClient();
      try {
        final uri = Uri(
          scheme: 'http',
          host: '127.0.0.1',
          port: server.port,
          path: path,
        );
        final req = await client.openUrl(method, uri);
        final res = await req.close();
        final bytes = await res.fold<List<int>>(
          <int>[],
          (acc, chunk) => acc..addAll(chunk),
        );
        return (statusCode: res.statusCode, headers: res.headers, body: bytes);
      } finally {
        client.close(force: true);
      }
    }

    test(
      'responds 200 ok on GET /healthz, HEAD /healthz, and HEAD /v1/caster with Cache-Control: no-store',
      () async {
        final res = await sendRequest('GET', '/healthz');
        check(res.statusCode).equals(HttpStatus.ok);
        check(
          res.headers.value(HttpHeaders.cacheControlHeader),
        ).equals('no-store');
        check(res.headers.value(castRevisionHeader)).isNull();
        check(utf8.decode(res.body)).equals('ok\n');

        final headHealth = await sendRequest('HEAD', '/healthz');
        check(headHealth.statusCode).equals(HttpStatus.ok);
        check(
          headHealth.headers.value(HttpHeaders.cacheControlHeader),
        ).equals('no-store');
        check(headHealth.headers.value(castRevisionHeader)).isNull();
        check(headHealth.body).isEmpty();

        final headCaster = await sendRequest('HEAD', '/v1/caster');
        check(headCaster.statusCode).equals(HttpStatus.ok);
        check(
          headCaster.headers.value(HttpHeaders.cacheControlHeader),
        ).equals('no-store');
        check(headCaster.headers.value(castRevisionHeader)).isNull();
        check(headCaster.body).isEmpty();

        final headClient = await sendRequest('HEAD', '/v1/client');
        check(headClient.statusCode).equals(HttpStatus.ok);
        check(
          headClient.headers.value(HttpHeaders.cacheControlHeader),
        ).equals('no-store');
        check(headClient.headers.value(castRevisionHeader)).isNull();
        check(headClient.body).isEmpty();

        final versionedServer = await CastServer.bind(
          ServerConfig(port: 0, revision: 'termui-cast-00007-xyz'),
        );
        addTearDown(versionedServer.close);

        final client = HttpClient();
        addTearDown(() => client.close(force: true));
        for (final (method, path) in const [
          ('GET', '/healthz'),
          ('HEAD', '/healthz'),
          ('HEAD', '/v1/caster'),
          ('HEAD', '/v1/client'),
        ]) {
          final req = await client.openUrl(
            method,
            Uri.parse('http://127.0.0.1:${versionedServer.port}$path'),
          );
          final resp = await req.close();
          await resp.drain<void>();
          check(resp.statusCode).equals(HttpStatus.ok);
          check(
            resp.headers.value(HttpHeaders.cacheControlHeader),
          ).equals('no-store');
          check(
            resp.headers.value(castRevisionHeader),
          ).equals('termui-cast-00007-xyz');
        }

        // Verify 101 Switching Protocols upgrade response includes x-cast-revision when configured,
        // and omits it when revision is null.
        final unversionedUpgradeReq = await client.getUrl(
          Uri.parse('http://127.0.0.1:${server.port}/v1/caster'),
        );
        unversionedUpgradeReq.headers
          ..set(HttpHeaders.connectionHeader, 'Upgrade')
          ..set(HttpHeaders.upgradeHeader, 'websocket')
          ..set('Sec-WebSocket-Version', '13')
          ..set('Sec-WebSocket-Key', 'dGhlIHNhbXBsZSBub25jZQ==');
        final unversionedUpgradeResp = await unversionedUpgradeReq.close();
        check(
          unversionedUpgradeResp.statusCode,
        ).equals(HttpStatus.switchingProtocols);
        check(
          unversionedUpgradeResp.headers.value(castRevisionHeader),
        ).isNull();
        final unversionedSocket = await unversionedUpgradeResp.detachSocket();
        unversionedSocket.destroy();

        final versionedUpgradeReq = await client.getUrl(
          Uri.parse('http://127.0.0.1:${versionedServer.port}/v1/caster'),
        );
        versionedUpgradeReq.headers
          ..set(HttpHeaders.connectionHeader, 'Upgrade')
          ..set(HttpHeaders.upgradeHeader, 'websocket')
          ..set('Sec-WebSocket-Version', '13')
          ..set('Sec-WebSocket-Key', 'dGhlIHNhbXBsZSBub25jZQ==');
        final versionedUpgradeResp = await versionedUpgradeReq.close();
        check(
          versionedUpgradeResp.statusCode,
        ).equals(HttpStatus.switchingProtocols);
        check(
          versionedUpgradeResp.headers.value(castRevisionHeader),
        ).equals('termui-cast-00007-xyz');
        final versionedSocket = await versionedUpgradeResp.detachSocket();
        versionedSocket.destroy();
      },
    );

    test(
      'serves index.html, .mjs, .wasm, .ttf, and SPA pass-through routes',
      () async {
        final rootRes = await sendRequest('GET', '/');
        check(rootRes.statusCode).equals(HttpStatus.ok);
        check(
          rootRes.headers.contentType?.mimeType,
        ).isNotNull().equals('text/html');
        check(
          rootRes.headers.value('referrer-policy'),
        ).isNotNull().equals('no-referrer');
        check(
          rootRes.headers.value('x-frame-options'),
        ).isNotNull().equals('DENY');
        check(
          rootRes.headers.value('cross-origin-opener-policy'),
        ).isNotNull().equals('same-origin');
        check(
          rootRes.headers.value('cross-origin-embedder-policy'),
        ).isNotNull().equals('require-corp');
        check(rootRes.headers.value('content-security-policy')).isNotNull()
          ..contains("script-src 'self' 'wasm-unsafe-eval'")
          ..contains("media-src 'self' blob: data:;")
          ..contains("manifest-src 'self';")
          ..contains("frame-ancestors 'none'")
          ..contains("worker-src 'self' blob:;");
        check(utf8.decode(rootRes.body)).contains('CastApp');

        final mjsRes = await sendRequest('GET', '/main.dart.mjs');
        check(mjsRes.statusCode).equals(HttpStatus.ok);
        check(
          mjsRes.headers.contentType?.mimeType,
        ).isNotNull().equals('application/javascript');

        final wasmRes = await sendRequest('GET', '/main.dart.wasm');
        check(wasmRes.statusCode).equals(HttpStatus.ok);
        check(
          wasmRes.headers.contentType?.mimeType,
        ).isNotNull().equals('application/wasm');
        check(
          wasmRes.body,
        ).deepEquals(const [0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00]);

        final fontRes = await sendRequest(
          'GET',
          '/assets/fonts/CascadiaMonoPL.ttf',
        );
        check(fontRes.statusCode).equals(HttpStatus.ok);
        check(
          fontRes.headers.contentType?.mimeType,
        ).isNotNull().equals('font/ttf');

        final spacedFontRes = await sendRequest(
          'GET',
          '/assets/fonts/Cascadia Mono.ttf',
        );
        check(spacedFontRes.statusCode).equals(HttpStatus.ok);
        check(spacedFontRes.body).deepEquals(const [5, 6, 7, 8]);

        final headRes = await sendRequest('HEAD', '/main.dart.wasm');
        check(headRes.statusCode).equals(HttpStatus.ok);
        check(headRes.body).isEmpty();
        check(headRes.headers.contentLength).equals(8);

        // Extensionless route passes through to SPA index.html.
        final spaRes = await sendRequest('GET', '/sessions/shell-1');
        check(spaRes.statusCode).equals(HttpStatus.ok);
        check(utf8.decode(spaRes.body)).contains('CastApp');
      },
    );

    test(
      'rejects traversal, missing assets, non-WebSocket /v1/*, and non-GET/HEAD methods',
      () async {
        final rawSocket = await Socket.connect('127.0.0.1', server.port);
        rawSocket.write(
          'GET /../secret.txt HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n',
        );
        await rawSocket.flush();
        final rawResponse = await utf8.decoder.bind(rawSocket).join();
        await rawSocket.close();
        check(rawResponse).contains('404 Not Found');
        check(rawResponse).not((it) => it.contains('TOP_SECRET'));

        final client = HttpClient();
        addTearDown(() => client.close(force: true));
        for (final encodedPath in const [
          '/..%2fsecret.txt',
          '/..%2fsecret',
          '/..%5csecret.txt',
        ]) {
          final encodedReq = await client.getUrl(
            Uri.parse('http://127.0.0.1:${server.port}$encodedPath'),
          );
          final encodedRes = await encodedReq.close();
          final encodedBody = await utf8.decoder.bind(encodedRes).join();
          check(encodedRes.statusCode).equals(HttpStatus.forbidden);
          check(encodedBody).not((it) => it.contains('TOP_SECRET'));
          check(encodedBody).not((it) => it.contains('CastApp'));
        }

        if (!Platform.isWindows) {
          final unreadable = File(p.join(webDir.path, 'unreadable.js'))
            ..writeAsStringSync('secret');
          await Process.run('chmod', ['000', unreadable.path]);
          addTearDown(() => Process.run('chmod', ['644', unreadable.path]));
          final unreadableRes = await sendRequest('GET', '/unreadable.js');
          check(unreadableRes.statusCode).equals(HttpStatus.forbidden);
        }

        final symlinkEscape = Link(p.join(webDir.path, 'escape.txt'))
          ..createSync(outsideSecret.path);
        addTearDown(() {
          if (symlinkEscape.existsSync()) symlinkEscape.deleteSync();
        });
        final symlinkRes = await sendRequest('GET', '/escape.txt');
        check(symlinkRes.statusCode).equals(HttpStatus.forbidden);
        check(
          utf8.decode(symlinkRes.body),
        ).not((it) => it.contains('TOP_SECRET'));

        final missingAsset = await sendRequest('GET', '/missing.wasm');
        check(missingAsset.statusCode).equals(HttpStatus.notFound);

        final nonUpgrade = await sendRequest('GET', '/v1/client');
        check(nonUpgrade.statusCode).equals(HttpStatus.badRequest);

        final postRes = await sendRequest('POST', '/index.html');
        check(postRes.statusCode).equals(HttpStatus.methodNotAllowed);
      },
    );

    test(
      'supports --*-token-file, emits argv token warnings, and serves WASM/JS with no-cache ETag + 304',
      () async {
        final tokenDir = Directory.systemTemp.createTempSync('cast_tok_files_');
        addTearDown(() => tokenDir.deleteSync(recursive: true));
        final casterTokFile = File(p.join(tokenDir.path, 'caster.tok'))
          ..writeAsStringSync('  file-caster-secret\n');
        final clientTokFile = File(p.join(tokenDir.path, 'client.tok'))
          ..writeAsStringSync('file-client-secret\n');

        final fromFiles = ServerConfig.fromArgs(
          [
            '--caster-token-file=${casterTokFile.path}',
            '--client-token-file=${clientTokFile.path}',
          ],
          environment: const {},
          currentDirectory: Directory.systemTemp,
        )!;
        check(fromFiles.casterToken).equals('file-caster-secret');
        check(fromFiles.clientToken).equals('file-client-secret');
        check(fromFiles.warnings).isEmpty();

        final fromArgv = ServerConfig.fromArgs(
          const ['--caster-token=argv-c', '--client-token=argv-v'],
          environment: const {},
          currentDirectory: Directory.systemTemp,
        )!;
        check(fromArgv.warnings.length).equals(2);

        check(
          () => ServerConfig.fromArgs(
            [
              '--caster-token=inline',
              '--caster-token-file=${casterTokFile.path}',
            ],
            environment: const {},
            currentDirectory: Directory.systemTemp,
          ),
        ).throws<FormatException>();

        final client = HttpClient();
        addTearDown(() => client.close(force: true));
        final wasmReq = await client.getUrl(
          Uri.parse('http://127.0.0.1:${server.port}/main.dart.wasm'),
        );
        final wasmRes = await wasmReq.close();
        await wasmRes.drain<void>();
        check(wasmRes.statusCode).equals(HttpStatus.ok);
        check(
          wasmRes.headers.value(HttpHeaders.cacheControlHeader),
        ).equals('no-cache');
        final etag = wasmRes.headers.value(HttpHeaders.etagHeader);
        check(etag).isNotNull().isNotEmpty();
        check(etag!.startsWith('W/')).isFalse();
        check(etag).equals(
          '"${sha256.convert(await File('${webDir.path}/main.dart.wasm').readAsBytes())}"',
        );

        final revalReq = await client.getUrl(
          Uri.parse('http://127.0.0.1:${server.port}/main.dart.wasm'),
        );
        revalReq.headers.set(HttpHeaders.ifNoneMatchHeader, etag);
        final revalRes = await revalReq.close();
        await revalRes.drain<void>();
        check(revalRes.statusCode).equals(HttpStatus.notModified);

        // D-09: Same byte length and same mtime across rebuilds produces a different strong SHA-256 ETag.
        final wasmFile = File('${webDir.path}/main.dart.wasm');
        final originalBytes = await wasmFile.readAsBytes();
        final originalModified = (await wasmFile.stat()).modified;
        final replacedBytes = Uint8List.fromList(originalBytes);
        replacedBytes[0] ^= 0xFF;
        await wasmFile.writeAsBytes(replacedBytes);
        await wasmFile.setLastModified(originalModified);
        final server2 = await CastServer.bind(
          ServerConfig(port: 0, webRoot: webDir.path),
        );
        addTearDown(server2.close);
        final wasmReq2 = await client.getUrl(
          Uri.parse('http://127.0.0.1:${server2.port}/main.dart.wasm'),
        );
        final wasmRes2 = await wasmReq2.close();
        await wasmRes2.drain<void>();
        check(
          wasmRes2.headers.value(HttpHeaders.etagHeader),
        ).not((it) => it.equals(etag));
      },
    );
  });
